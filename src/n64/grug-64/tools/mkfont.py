#!/usr/bin/env python3
"""Bake the HUD font for Grug 64 into font.h: one-bit glyphs with the black outline built in.

    python3 tools/mkfont.py [font.ttf] [pixel size]

Each glyph is stored as rows of two bit masks (fill, outline ring), so the game draws outlined text in one pass.
The default is DejaVu Sans Bold (any bold sans .ttf works: pass the site's Allo as a .ttf to use it instead).
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
font_path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
size = int(sys.argv[2]) if len(sys.argv) > 2 else 8
font = ImageFont.truetype(font_path, size)
asc, desc = font.getmetrics()
CH = asc + desc
glyphs = []
for code in range(32, 127):
    ch = chr(code)
    adv = max(1, round(font.getlength(ch)))
    img = Image.new('1', (adv + 4, CH + 2), 0)
    d = ImageDraw.Draw(img); d.fontmode = '1'
    d.text((1, 1), ch, font=font, fill=1)
    px = img.load()
    w = adv + 2
    fill = [[1 if px[x, y] else 0 for x in range(w)] for y in range(CH + 2)]
    ring = [[0] * w for _ in range(CH + 2)]
    for y in range(CH + 2):
        for x in range(w):
            if fill[y][x]: continue
            if any(0 <= y + dy < CH + 2 and 0 <= x + dx < w and fill[y + dy][x + dx] for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                ring[y][x] = 1
    glyphs.append((adv, w, fill, ring))

# trim empty rows shared by every glyph (top and bottom)
H = CH + 2
used = [any(any(g[2][y]) or any(g[3][y]) for g in glyphs) for y in range(H)]
top = next(i for i, u in enumerate(used) if u); bot = H - next(i for i, u in enumerate(reversed(used)) if u)
rows = bot - top
out = ['/* Generated by tools/mkfont.py from %s at %d px: do not edit. */' % (os.path.basename(font_path), size),
       '#ifndef GRUG64_FONT_H', '#define GRUG64_FONT_H', '#include <stdint.h>',
       '#define FONT_ROWS %d' % rows, '#define FONT_FIRST 32', '#define FONT_COUNT %d' % len(glyphs),
       'typedef struct { uint8_t adv, w; uint16_t fill[FONT_ROWS], ring[FONT_ROWS]; } Glyph;',
       'static const Glyph FONT[FONT_COUNT] = {']
for code, (adv, w, fill, ring) in zip(range(32, 127), glyphs):
    assert w <= 16, (chr(code), w)
    f = ','.join('0x%04x' % sum(b << (15 - x) for x, b in enumerate(fill[y])) for y in range(top, bot))
    r = ','.join('0x%04x' % sum(b << (15 - x) for x, b in enumerate(ring[y])) for y in range(top, bot))
    out.append('  { %d, %d, {%s}, {%s} },   /* %s */' % (adv, w, f, r, chr(code) if chr(code) not in '\\/*' else 'x%02x' % code))
out += ['};', '#endif', '']
open(os.path.join(HERE, '..', 'font.h'), 'w').write('\n'.join(out))

# a preview sheet, to check the glyphs by eye
if len(sys.argv) > 3:
    text = ['GRUG BASEPLATE  HEALTH  JUMP HEIGHTS', 'Space: jump 7.2 studs · 8 is too high', 'Last jump: 7.2 studs up, 8.6 along 0123456789', 'the quick brown fox jumps over the lazy dog!?']
    S = 3; im = Image.new('RGB', (330 * S, (rows + 2) * len(text) * S + 8), (120, 160, 200)); p = im.load()
    for li, line in enumerate(text):
        x = 4
        for c in line:
            if not 32 <= ord(c) < 127: c = '-'
            adv, w, fill, ring = glyphs[ord(c) - 32]
            for y in range(top, bot):
                for xx in range(w):
                    col = (255, 255, 255) if fill[y][xx] else (0, 0, 0) if ring[y][xx] else None
                    if col:
                        for sy in range(S):
                            for sx in range(S): p[(x + xx) * S + sx, (li * (rows + 2) + y - top) * S + sy + 4] = col
            x += adv
    im.save(sys.argv[3])
print('font.h: %d glyphs, %d rows' % (len(glyphs), rows))
